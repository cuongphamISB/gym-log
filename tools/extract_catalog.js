// Extract the exercise catalog + images from the old ChatGPT-made HTML (v4.1)
// into js/seed.js and img/*.jpg.  Usage: node tools/extract_catalog.js <old.html>
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) { console.error('usage: node tools/extract_catalog.js <Fitness_Coach_Mobile_v4_1_Tracking.html>'); process.exit(1); }
const html = fs.readFileSync(src, 'utf8');
const m = html.match(/<script type="application\/json" id="catalog">([\s\S]*?)<\/script>/);
if (!m) throw new Error('catalog block not found');
const sessions = JSON.parse(m[1]);
const root = path.join(__dirname, '..');

// Hand-assigned type / muscles / rest (s) per exercise id.
// type: weight | unilateral | bodyweight | band | cardio | info
const META = {
  'strength-a-0': ['weight', ['Ngực', 'Tay sau', 'Vai']],
  'strength-a-1': ['unilateral', ['Lưng', 'Tay trước']],
  'strength-a-2': ['weight', ['Đùi trước', 'Mông', 'Core']],
  'strength-a-3': ['weight', ['Vai']],
  'strength-a-4': ['bodyweight', ['Core']],
  'strength-b-0': ['weight', ['Đùi sau', 'Mông', 'Lưng']],
  'strength-b-1': ['weight', ['Ngực', 'Vai', 'Tay sau']],
  'strength-b-2': ['unilateral', ['Đùi trước', 'Mông']],
  'strength-b-3': ['weight', ['Vai', 'Lưng']],
  'strength-b-4': ['weight', ['Tay trước']],
  'strength-c-0': ['bodyweight', ['Ngực', 'Tay sau', 'Core']],
  'strength-c-1': ['unilateral', ['Đùi trước', 'Mông']],
  'strength-c-2': ['weight', ['Vai', 'Tay sau']],
  'strength-c-3': ['weight', ['Bắp chân']],
  'strength-c-4': ['cardio', ['Toàn thân']],
  'outdoor-0': ['band', ['Lưng', 'Tay trước']],
  'outdoor-1': ['band', ['Vai', 'Lưng']],
  'outdoor-2': ['band', ['Lưng']],
  'outdoor-3': ['band', ['Core']],
  'outdoor-4': ['bodyweight', ['Lưng', 'Tay trước']],
  'outdoor-5': ['bodyweight', ['Core']],
  'cardio-0': ['cardio', ['Cardio']],
  'cardio-1': ['cardio', ['Cardio']],
  'cardio-2': ['cardio', ['Mobility']],
  'cardio-3': ['info', []],
};
const DAYS = { 'strength-a': [1], 'strength-b': [3], 'strength-c': [5], outdoor: [6], cardio: [2, 0] };
const ICON = { 'strength-a': 'A', 'strength-b': 'B', 'strength-c': 'C', outdoor: 'O', cardio: 'R' };

function parseDosage(d) {
  const out = { sets: 3, repLow: null, repHigh: null, rest: 90 };
  const sm = d.match(/(\d+)(?:\s*[–-]\s*(\d+))?\s*(?:hiệp|vòng)/);
  if (sm) out.sets = Number(sm[2] || sm[1]);
  const rm = d.match(/×\s*(\d+)(?:\s*[–-]\s*(\d+))?/);
  if (rm) { out.repLow = Number(rm[1]); out.repHigh = Number(rm[2] || rm[1]); }
  const restm = d.match(/nghỉ\s*(\d+)/);
  if (restm) out.rest = Number(restm[1]);
  return out;
}

const exercises = [];
const templates = [];
for (const s of sessions) {
  const items = [];
  for (const c of s.cards) {
    const meta = META[c.id];
    if (!meta) throw new Error('no META for ' + c.id);
    const [type, muscles] = meta;
    const mm = c.image.match(/^data:image\/(\w+);base64,(.*)$/);
    let image = null;
    if (mm) {
      const ext = mm[1] === 'jpeg' ? 'jpg' : mm[1];
      image = `img/${c.id}.${ext}`;
      fs.writeFileSync(path.join(root, image), Buffer.from(mm[2], 'base64'));
    }
    exercises.push({ id: c.id, name: c.name, type, muscles, focus: c.focus, dosage: c.dosage, guide: c.details, image });
    if (type !== 'info') {
      const p = parseDosage(c.dosage);
      if (type === 'cardio') { p.sets = 1; p.repLow = p.repHigh = null; }
      items.push({ exerciseId: c.id, sets: p.sets, repLow: p.repLow, repHigh: p.repHigh, rest: p.rest });
    }
  }
  templates.push({ id: s.id, name: s.title, short: ICON[s.id], note: s.subtitle, days: DAYS[s.id] || [], items });
}

const out = '// Generated by tools/extract_catalog.js — do not edit by hand.\n' +
  'self.SEED = ' + JSON.stringify({ exercises, templates }, null, 1) + ';\n';
fs.writeFileSync(path.join(root, 'js/seed.js'), out);
console.log(`exercises: ${exercises.length}, templates: ${templates.length}`);
for (const t of templates) console.log(t.id, t.items.map(i => `${i.exerciseId}:${i.sets}x${i.repLow}-${i.repHigh}/${i.rest}s`).join(' '));
